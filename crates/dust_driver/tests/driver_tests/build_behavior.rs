use dust_driver::{BuildRequest, CleanRequest, run_build, run_clean};

use super::support::{DustImport, make_workspace, write_dust_file, write_file};

#[test]
fn changed_tool_hash_rebuilds_cached_output_without_changing_generated_bytes() {
    let workspace = make_workspace();
    let root = workspace.path();
    let source = root.join("lib/user.dart");
    write_dust_file(
        &source,
        &[DustImport::Derive],
        "part 'user.g.dart';\n@ToString()\nclass User { final String id; const User(this.id); }\n",
    );
    let build = || {
        run_build(BuildRequest {
            cwd: root.to_path_buf(),
            fail_fast: true,
            jobs: None,
            db: Default::default(),
        })
    };
    assert_eq!(build().diagnostics, []);
    let cached = build();
    assert_eq!(cached.diagnostics, []);
    assert_eq!(cached.cache.as_ref().unwrap().hits, 1);
    let output = root.join("lib/user.g.dart");
    let expected = std::fs::read(&output).unwrap();
    let mut cache = dust_cache::WorkspaceCache::load(root).unwrap();
    let original = cache.get(root, &source).unwrap().clone();
    let mut outdated = original.clone();
    outdated.tool_hash ^= 1;
    cache.insert(root, &source, outdated);
    cache.flush().unwrap();

    let rebuilt = build();
    assert_eq!(rebuilt.diagnostics, []);
    assert_eq!(rebuilt.cache.as_ref().unwrap().hits, 0);
    assert_eq!(rebuilt.cache.as_ref().unwrap().misses, 1);
    assert!(!rebuilt.build_artifacts[0].cached);
    assert_eq!(std::fs::read(&output).unwrap(), expected);
    let repaired = dust_cache::WorkspaceCache::load(root).unwrap();
    assert_eq!(repaired.get(root, &source), Some(&original));
    let cached_again = build();
    assert_eq!(cached_again.diagnostics, []);
    assert_eq!(cached_again.cache.as_ref().unwrap().hits, 1);
}

#[test]
fn second_build_uses_persistent_cache_under_dot_dart_tool() {
    let workspace = make_workspace();
    write_dust_file(
        &workspace.path().join("lib/user.dart"),
        &[DustImport::Derive],
        "part 'user.g.dart';\n\
         @ToString()\n\
         class User {\n\
           final String id;\n\
           const User(this.id);\n\
         }\n",
    );

    let first = run_build(BuildRequest {
        cwd: workspace.path().to_path_buf(),
        fail_fast: false,
        jobs: Some(4),
        db: Default::default(),
    });
    let second = run_build(BuildRequest {
        cwd: workspace.path().to_path_buf(),
        fail_fast: false,
        jobs: Some(4),
        db: Default::default(),
    });

    assert!(!first.has_errors());
    assert!(!second.has_errors());
    assert!(
        workspace
            .path()
            .join(".dart_tool/dust/build_cache_v1.json")
            .exists()
    );
    assert!(first.build_artifacts[0].written);
    assert!(!second.build_artifacts[0].written);
    assert!(second.build_artifacts[0].cached);
    assert_eq!(second.cache.as_ref().unwrap().hits, 1);
    assert_eq!(second.cache.as_ref().unwrap().misses, 0);
}

#[test]
fn clean_removes_dust_outputs_and_cache_but_keeps_foreign_generated_files() {
    let workspace = make_workspace();
    write_dust_file(
        &workspace.path().join("lib/user.dart"),
        &[DustImport::Derive],
        "part 'user.g.dart';\n\
         @ToString()\n\
         class User {\n\
           final String id;\n\
           const User(this.id);\n\
         }\n",
    );

    let built = run_build(BuildRequest {
        cwd: workspace.path().to_path_buf(),
        fail_fast: false,
        jobs: None,
        db: Default::default(),
    });
    assert!(!built.has_errors());

    let foreign_output = workspace.path().join("lib/foreign.g.dart");
    write_file(&foreign_output, "// generated by someone else\n");
    // The query cache is a committed build input, not a build artifact: a
    // checkout with no database validates its SQL from it, so clean must leave
    // it where it is.
    let query_cache = workspace
        .path()
        .join(".dust_sql/users-0123456789abcdef.json");
    write_file(&query_cache, "{\"version\": 3, \"entries\": []}\n");
    assert!(
        workspace
            .path()
            .join(".dart_tool/dust/build_cache_v1.json")
            .exists()
    );

    let result = run_clean(CleanRequest {
        cwd: workspace.path().to_path_buf(),
    });

    assert!(!result.has_errors());
    let clean = result.clean.as_ref().unwrap();
    assert_eq!(clean.scanned_files, 2);
    assert_eq!(clean.removed_files, 1);
    assert!(clean.cache_cleared);
    assert!(!workspace.path().join("lib/user.g.dart").exists());
    assert!(foreign_output.exists());
    assert!(query_cache.exists());
    assert!(!workspace.path().join(".dart_tool/dust").exists());
}

#[test]
fn parallel_build_keeps_artifact_order_deterministic() {
    let workspace = make_workspace();
    write_dust_file(
        &workspace.path().join("lib/z_team.dart"),
        &[DustImport::Derive],
        "part 'z_team.g.dart';\n\
         @CopyWith()\n\
         class Team {\n\
           final String id;\n\
           const Team(this.id);\n\
         }\n",
    );
    write_dust_file(
        &workspace.path().join("lib/a_user.dart"),
        &[DustImport::Derive],
        "part 'a_user.g.dart';\n\
         @ToString()\n\
         class User {\n\
           final String id;\n\
           const User(this.id);\n\
         }\n",
    );

    let result = run_build(BuildRequest {
        cwd: workspace.path().to_path_buf(),
        fail_fast: false,
        jobs: Some(4),
        db: Default::default(),
    });

    let outputs = result
        .build_artifacts
        .iter()
        .map(|artifact| artifact.output_path.clone())
        .collect::<Vec<_>>();

    assert_eq!(
        outputs,
        vec![
            workspace.path().join("lib/a_user.g.dart"),
            workspace.path().join("lib/z_team.g.dart"),
        ]
    );
}

#[test]
fn build_skips_invalid_library_and_continues_when_fail_fast_is_false() {
    let workspace = make_workspace();
    write_dust_file(
        &workspace.path().join("lib/bad.dart"),
        &[DustImport::Derive],
        "part 'bad.g.dart';\n\
         @CopyWith()\n\
         class Broken {\n\
           final String id;\n\
           final int age;\n\
           const Broken(this.id);\n\
         }\n",
    );
    write_dust_file(
        &workspace.path().join("lib/good.dart"),
        &[DustImport::Derive],
        "part 'good.g.dart';\n\
         @CopyWith()\n\
         class Good {\n\
           final String id;\n\
           const Good(this.id);\n\
         }\n",
    );

    let result = run_build(BuildRequest {
        cwd: workspace.path().to_path_buf(),
        fail_fast: false,
        jobs: None,
        db: Default::default(),
    });

    assert!(result.has_errors());
    assert!(result.diagnostics.iter().any(|diagnostic| {
        diagnostic.message.contains(
            "`CopyWith` requires a constructor that accepts every field on class `Broken`",
        )
    }));
    assert!(!workspace.path().join("lib/bad.g.dart").exists());
    assert!(workspace.path().join("lib/good.g.dart").exists());
}

#[test]
fn build_stops_after_first_error_when_fail_fast_is_true() {
    let workspace = make_workspace();
    write_dust_file(
        &workspace.path().join("lib/a_bad.dart"),
        &[DustImport::Derive],
        "part 'a_bad.g.dart';\n\
         @CopyWith()\n\
         class Broken {\n\
           final String id;\n\
           final int age;\n\
           const Broken(this.id);\n\
         }\n",
    );
    write_dust_file(
        &workspace.path().join("lib/z_good.dart"),
        &[DustImport::Derive],
        "part 'z_good.g.dart';\n\
         @CopyWith()\n\
         class Good {\n\
           final String id;\n\
           const Good(this.id);\n\
         }\n",
    );

    let result = run_build(BuildRequest {
        cwd: workspace.path().to_path_buf(),
        fail_fast: true,
        jobs: None,
        db: Default::default(),
    });

    assert!(result.has_errors());
    assert_eq!(result.build_artifacts.len(), 1);
    assert!(result.diagnostics.iter().any(|diagnostic| {
        diagnostic.message.contains(
            "`CopyWith` requires a constructor that accepts every field on class `Broken`",
        )
    }));
}
