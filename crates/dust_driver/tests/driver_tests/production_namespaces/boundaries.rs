use std::fs;

use super::{MODEL, build, workspace, write_file};

#[test]
fn transparent_external_alias_keeps_exact_direct_generation() {
    let workspace = workspace();
    let root = workspace.path();
    let model = root.join("lib/model.dart");
    write_file(
        &model,
        &format!("import 'package:dust_dart/derive.dart';\n{MODEL}"),
    );
    assert_eq!(build(root).diagnostics, []);
    let expected = fs::read(root.join("lib/model.g.dart")).unwrap();
    write_file(
        &root.join("deps/bridge/lib/bridge.dart"),
        "export 'definition.dart' show Pretty;",
    );
    write_file(
        &root.join("deps/bridge/lib/definition.dart"),
        "import 'package:dust_dart/derive.dart' as d; typedef Pretty=d.ToString;",
    );
    write_file(
        &model,
        &format!(
            "import 'package:bridge/bridge.dart' as b;\n{}",
            MODEL.replace("@Derive([ToString()])", "@b.Pretty()")
        ),
    );
    assert_eq!(build(root).diagnostics, []);
    assert_eq!(fs::read(root.join("lib/model.g.dart")).unwrap(), expected);
}

#[test]
fn foreign_generated_part_may_define_a_transparent_annotation_alias() {
    let workspace = workspace();
    let root = workspace.path();
    let model = root.join("lib/model.dart");
    write_file(
        &model,
        &format!("import 'package:dust_dart/derive.dart';\n{MODEL}"),
    );
    assert_eq!(build(root).diagnostics, []);
    let expected = fs::read(root.join("lib/model.g.dart")).unwrap();
    let part = "// Generated by another tool.\npart of 'model.dart'; typedef Pretty=d.ToString;";
    write_file(&root.join("lib/annotations.g.dart"), part);
    write_file(
        &model,
        &format!(
            "import 'package:dust_dart/derive.dart' as d;\npart 'annotations.g.dart';\n{}",
            MODEL.replace("@Derive([ToString()])", "@Pretty()")
        ),
    );
    assert_eq!(build(root).diagnostics, []);
    assert_eq!(fs::read(root.join("lib/model.g.dart")).unwrap(), expected);
    assert_eq!(
        fs::read_to_string(root.join("lib/annotations.g.dart")).unwrap(),
        part
    );
}

#[test]
fn stale_dust_output_cannot_define_an_annotation_or_mutate_successful_state() {
    let workspace = workspace();
    let root = workspace.path();
    let model = root.join("lib/model.dart");
    write_file(
        &model,
        &format!("import 'package:dust_dart/derive.dart';\n{MODEL}"),
    );
    assert_eq!(build(root).diagnostics, []);
    let path = root.join("lib/model.g.dart");
    let mut stale = fs::read_to_string(&path).unwrap();
    stale.push_str("\nclass Ghost { const Ghost(); }\n");
    write_file(&path, &stale);
    let cache_path = root.join(".dart_tool/dust/build_cache_v1.json");
    let cache = fs::read(&cache_path).unwrap();
    write_file(
        &model,
        &format!(
            "import 'package:dust_dart/derive.dart';\n{}",
            MODEL.replace("@Derive", "@Ghost()\n@Derive")
        ),
    );
    let result = build(root);
    assert_eq!(
        result
            .diagnostics
            .iter()
            .map(|error| error.message.as_str())
            .collect::<Vec<_>>(),
        ["annotation name `Ghost` is not visible in this namespace"]
    );
    assert!(result.has_errors());
    assert_eq!(fs::read_to_string(path).unwrap(), stale);
    assert_eq!(fs::read(cache_path).unwrap(), cache);
}

#[test]
fn own_generated_model_types_are_not_annotation_provenance() {
    let workspace = workspace();
    let root = workspace.path();
    write_file(&root.join("lib/model.dart"), "import 'package:dust_dart/derive.dart'; part 'model.g.dart';
      @Derive([CopyWith(), ToString()]) class Model with _$Model {
        const Model(this.value, {this.previous}); final int value; final _$ModelCopyWith<Model>? previous; }");
    assert_eq!(build(root).diagnostics, []);
    let expected = fs::read(root.join("lib/model.g.dart")).unwrap();
    let warm = build(root);
    assert_eq!(warm.diagnostics, []);
    assert_eq!(warm.cache.unwrap().hits, 1);
    assert_eq!(fs::read(root.join("lib/model.g.dart")).unwrap(), expected);
}

#[test]
fn short_header_auxiliary_output_cannot_supply_annotation_provenance() {
    let workspace = workspace();
    let root = workspace.path();
    let model = root.join("lib/model.dart");
    write_file(
        &model,
        &format!("import 'package:dust_dart/derive.dart';\n{MODEL}"),
    );
    assert_eq!(build(root).diagnostics, []);
    let output_path = root.join("lib/model.g.dart");
    let cache_path = root.join(".dart_tool/dust/build_cache_v1.json");
    let output = fs::read(&output_path).unwrap();
    let cache = fs::read(&cache_path).unwrap();
    let auxiliary = "// GENERATED CODE - DO NOT MODIFY BY HAND.\n// Generated by dust.\n//\nclass Ghost { const Ghost(); }\n";
    let auxiliary_path = root.join("lib/auxiliary.g.dart");
    write_file(&auxiliary_path, auxiliary);
    write_file(
        &model,
        &format!(
            "import 'package:dust_dart/derive.dart'; import 'auxiliary.g.dart';\n{}",
            MODEL.replace("@Derive", "@Ghost()\n@Derive")
        ),
    );
    let checked = dust_driver::run_check(dust_driver::CheckRequest {
        sdk_source_root: Some(root.join("sdk")),
        cwd: root.into(),
        fail_fast: false,
        jobs: None,
        db: Default::default(),
    });
    for result in [build(root), checked] {
        assert!(result.has_errors());
        assert_eq!(
            result
                .diagnostics
                .iter()
                .map(|error| error.message.as_str())
                .collect::<Vec<_>>(),
            ["annotation name `Ghost` is not visible in this namespace"]
        );
        assert!(
            !result
                .diagnostic_files
                .iter()
                .any(|file| file.path == auxiliary_path)
        );
    }
    assert_eq!(fs::read(output_path).unwrap(), output);
    assert_eq!(fs::read(cache_path).unwrap(), cache);
    assert_eq!(fs::read_to_string(auxiliary_path).unwrap(), auxiliary);
}

#[test]
fn missing_required_barrel_is_an_error_not_discovery_loss_or_legacy_fallback() {
    let workspace = workspace();
    let root = workspace.path();
    write_file(
        &root.join("lib/model.dart"),
        &format!("import 'package:bridge/bridge.dart';\n{MODEL}"),
    );
    assert_eq!(build(root).diagnostics, []);
    let output = fs::read(root.join("lib/model.g.dart")).unwrap();
    let cache_path = root.join(".dart_tool/dust/build_cache_v1.json");
    let cache = fs::read(&cache_path).unwrap();
    fs::remove_file(root.join("deps/bridge/lib/bridge.dart")).unwrap();
    let failed = build(root);
    assert!(failed.has_errors(), "{:?}", failed.diagnostics);
    assert!(
        failed
            .diagnostics
            .iter()
            .all(|error| error.message.contains("cannot read namespace source"))
    );
    assert_eq!(fs::read(root.join("lib/model.g.dart")).unwrap(), output);
    assert_eq!(fs::read(cache_path).unwrap(), cache);
}

#[test]
fn ambiguity_retains_all_dependency_source_labels() {
    let workspace = workspace();
    let root = workspace.path();
    write_file(
        &root.join("lib/model.dart"),
        &format!(
            "import 'package:dust_dart/derive.dart'; import 'package:bridge/bridge.dart' as t;\n{}",
            MODEL.replace("[ToString()]", "[t.ToString()]")
        ),
    );
    write_file(
        &root.join("deps/bridge/lib/bridge.dart"),
        "export 'package:dust_dart/derive.dart'; export 'foreign.dart';",
    );
    write_file(
        &root.join("deps/bridge/lib/foreign.dart"),
        "class ToString { const ToString(); }",
    );
    let result = build(root);
    assert!(result.has_errors());
    assert_eq!(
        result
            .diagnostics
            .iter()
            .map(|error| error.message.as_str())
            .collect::<Vec<_>>(),
        ["annotation `ToString` is ambiguous between distinct declarations"]
    );
    for label in &result.diagnostics[0].labels {
        assert!(
            result
                .diagnostic_files
                .iter()
                .any(|file| file.file_id == label.file_id),
            "{label:?}"
        );
    }
    assert!(
        result
            .diagnostic_files
            .iter()
            .any(|file| file.path.ends_with("deps/bridge/lib/foreign.dart"))
    );
    assert!(!root.join("lib/model.g.dart").exists());
}
