/// Uneven native parsing and cached decoding retain canonical facts and labels.
mod dynamic;

fn fixture(
    text: &str,
) -> (
    tempfile::TempDir,
    SourceIndex,
    Source,
    BTreeMap<PathBuf, Arc<str>>,
) {
    let root = tempfile::tempdir().unwrap();
    crate::namespace_sources::test_workspace::prepare(root.path(), root.path(), "example");
    let path = root.path().join("lib/model.dart");
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(&path, text).unwrap();
    let index = SourceIndex::load(
        root.path(),
        &root.path().join(".dart_tool/package_config.json"),
        Some(&root.path().join(".dust-test-sdk")),
        false,
    )
    .unwrap();
    let mut source = index.file(&path).unwrap();
    source.language_version = DartLanguageVersion::DART_3_12;
    (
        root,
        index,
        source,
        BTreeMap::from([(path, Arc::from(text))]),
    )
}

#[test]
fn preparation_preserves_planning_result_and_rebinds_both_diagnostic_views() {
    let (_root, index, source, snapshots) = fixture("class Broken {");
    let (planned, mut prepared) = prepare_roots(
        &index,
        std::slice::from_ref(&source),
        2,
        &[],
        &snapshots,
        None,
        || Err::<(), _>("output planning failed"),
    );
    assert_eq!(planned, Err("output planning failed"));
    let input = SourceInput::read(&source, None, &Default::default()).unwrap();
    let id = FileId::new(42);
    let (parsed, _) = prepared.take(&source, Some(&input), id).unwrap();
    assert!(!parsed.diagnostics.is_empty());
    assert!(!parsed.namespace_diagnostics.is_empty());
    assert!(
        parsed
            .diagnostics
            .iter()
            .chain(&parsed.namespace_diagnostics)
            .flat_map(|diagnostic| &diagnostic.labels)
            .all(|label| label.file_id == id)
    );
    assert!(!prepared.contains(&source.uri));
}

#[test]
fn changed_marked_deleted_and_late_owned_roots_discard_cached_facts() {
    for replacement in [
        Some("class Changed {}"),
        Some("// GENERATED CODE - DO NOT MODIFY BY HAND\n// Generated by dust.\nclass Changed {}"),
        None,
    ] {
        let (_root, index, source, snapshots) = fixture("class Model {}");
        let (_, mut prepared) = prepare_roots(
            &index,
            std::slice::from_ref(&source),
            2,
            &[],
            &snapshots,
            None,
            || {
                if let Some(text) = replacement {
                    std::fs::write(&source.path, text).unwrap();
                } else {
                    std::fs::remove_file(&source.path).unwrap();
                }
            },
        );
        let input = SourceInput::read(&source, None, &Default::default());
        assert!(
            prepared
                .take(&source, input.as_ref().ok(), FileId::new(3))
                .is_none()
        );
        assert!(!prepared.contains(&source.uri));
    }
    let (_root, index, source, snapshots) = fixture("class Model {}");
    let (_, mut prepared) = prepare_roots(
        &index,
        std::slice::from_ref(&source),
        2,
        &[],
        &snapshots,
        None,
        || (),
    );
    let owned = SourceInput::read(
        &source,
        Some("file:///owner.dart".into()),
        &Default::default(),
    )
    .unwrap();
    assert!(
        prepared
            .take(&source, Some(&owned), FileId::new(4))
            .is_none()
    );
}

#[test]
fn equal_paths_keep_distinct_uri_facts_and_language_options() {
    let (_root, index, source, snapshots) = fixture("class Model { Model(var value); }");
    let mut other = source.clone();
    other.uri = "package:example/model.dart".into();
    other.language_version = DartLanguageVersion::DART_3_13;
    let roots = [source.clone(), other.clone()];
    let (_, mut prepared) = prepare_roots(&index, &roots, 2, &[], &snapshots, None, || ());
    assert_eq!(prepared.uris().count(), 2);
    let input = SourceInput::read(&source, None, &Default::default()).unwrap();
    let (parsed, _) = prepared
        .take(&other, Some(&input), FileId::new(13))
        .unwrap();
    assert_eq!(parsed.options.language_version, other.language_version);
    assert!(prepared.contains(&source.uri));
    let (parsed, _) = prepared
        .take(&source, Some(&input), FileId::new(12))
        .unwrap();
    assert_eq!(parsed.options.language_version, source.language_version);

    let (_, mut prepared) = prepare_roots(
        &index,
        std::slice::from_ref(&source),
        1,
        &[],
        &snapshots,
        None,
        || (),
    );
    let mut changed = source;
    changed.language_version = DartLanguageVersion::DART_3_13;
    assert!(
        prepared
            .take(&changed, Some(&input), FileId::new(14))
            .is_none()
    );
}
