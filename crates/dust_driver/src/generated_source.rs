/// Both primary and auxiliary Dust outputs carry these leading ownership markers.
pub(crate) fn is_dust_generated_source(contents: &str) -> bool {
    contents.starts_with("// GENERATED CODE - DO NOT MODIFY BY HAND")
        && contents
            .lines()
            .take(20)
            .any(|line| line.starts_with("// Generated by dust."))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generated_ownership_is_not_a_suffix_or_an_arbitrary_body_comment() {
        assert!(is_dust_generated_source(dust_plugin_api::GENERATED_HEADER));
        assert!(is_dust_generated_source(
            "// GENERATED CODE - DO NOT MODIFY BY HAND.\n// Generated by dust.\n"
        ));
        assert!(!is_dust_generated_source(
            "part of 'x.dart';\n// Generated by dust.\n"
        ));
        assert!(!is_dust_generated_source(
            "// GENERATED CODE - DO NOT MODIFY BY HAND\n// Someone else\n"
        ));
        assert!(!is_dust_generated_source(&format!(
            "// GENERATED CODE - DO NOT MODIFY BY HAND\n{}// Generated by dust.\n",
            "// padding\n".repeat(20)
        )));
    }
}
