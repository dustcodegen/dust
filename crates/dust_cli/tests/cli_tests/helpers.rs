use std::fs;

use tempfile::tempdir;

#[path = "../../../../fixtures/namespace_sources/workspace.rs"]
mod namespace_fixture;
pub(crate) use namespace_fixture::{prepare, set_language_version};

/// Exercise real CLI dispatch with an SDK fixture scoped to this child process.
pub(crate) fn run_cli(args: impl IntoIterator<Item = impl Into<String>>) -> dust_cli::CliRun {
    let args = args.into_iter().map(Into::into).collect::<Vec<_>>();
    let root = args
        .windows(2)
        .find(|pair| pair[0] == "--root")
        .map(|pair| pair[1].as_str())
        .or_else(|| args.iter().find_map(|arg| arg.strip_prefix("--root=")));
    let mut command = std::process::Command::new(env!("CARGO_BIN_EXE_dust"));
    command.args(&args);
    if let Some(root) = root {
        let sdk = namespace_fixture::sdk_source_root(std::path::Path::new(root));
        if sdk.join("version").is_file() {
            let mut paths = vec![fs::canonicalize(sdk.join("bin")).unwrap()];
            paths.extend(
                std::env::var_os("PATH")
                    .as_deref()
                    .into_iter()
                    .flat_map(std::env::split_paths),
            );
            command.env("PATH", std::env::join_paths(paths).unwrap());
        }
    }
    let output = command.output().unwrap();
    dust_cli::CliRun {
        exit_code: output.status.code().expect("CLI exited normally"),
        stdout: String::from_utf8(output.stdout).unwrap(),
        stderr: String::from_utf8(output.stderr).unwrap(),
    }
}

pub(crate) enum DustImport {
    Derive,
    Route,
}

pub(crate) fn owned_output(body: &str) -> String {
    format!("// GENERATED CODE - DO NOT MODIFY BY HAND.\n// Generated by dust.\n{body}")
}

pub(crate) fn write_dust_file(path: &std::path::Path, imports: &[DustImport], contents: &str) {
    let import_block = imports
        .iter()
        .map(|import| match import {
            DustImport::Derive => "import 'package:dust_dart/serde.dart';\n",
            DustImport::Route => "import 'package:dust_flutter/route.dart';\n",
        })
        .collect::<String>();
    write_file(path, &format!("{import_block}{contents}"));
}

pub(crate) fn write_file(path: &std::path::Path, contents: &str) {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).expect("create parent dirs");
    }
    fs::write(path, contents).expect("write file");
}

pub(crate) fn make_workspace() -> tempfile::TempDir {
    let root = tempdir().unwrap();
    write_file(&root.path().join("pubspec.yaml"), "name: dust_test\n");
    prepare(root.path(), root.path(), "dust_test");
    root
}

pub(crate) fn make_pub_workspace_member() -> (tempfile::TempDir, std::path::PathBuf) {
    let root = tempdir().unwrap();
    write_file(
        &root.path().join("pubspec.yaml"),
        "name: dust_workspace\nworkspace:\n  - examples/product_showcase\n",
    );
    write_file(
        &root.path().join(".dart_tool/package_config.json"),
        "{\"configVersion\":2,\"packages\":[]}\n",
    );
    let package_root = root.path().join("examples/product_showcase");
    write_file(
        &package_root.join("pubspec.yaml"),
        "name: product_showcase\nresolution: workspace\n",
    );
    write_file(
        &package_root.join(".dart_tool/package_graph.json"),
        "{\"configVersion\":1,\"roots\":[\"product_showcase\"],\"packages\":[]}\n",
    );
    prepare(root.path(), &package_root, "product_showcase");
    (root, package_root)
}
