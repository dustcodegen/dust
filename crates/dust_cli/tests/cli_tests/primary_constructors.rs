use crate::helpers::run_cli;

use super::helpers::{DustImport, make_workspace, write_dust_file, write_file};

#[test]
fn ambiguous_copy_labels_fail_without_replacing_generated_output() {
    let workspace = make_workspace();
    write_file(
        &workspace.path().join("pubspec.yaml"),
        "name: dust_test\nenvironment:\n  sdk: '>=3.13.0 <4.0.0'\n",
    );
    let output = workspace.path().join("lib/user.g.dart");
    let previous = super::helpers::owned_output("previous output\n");
    write_file(&output, &previous);
    write_dust_file(
        &workspace.path().join("lib/user.dart"),
        &[DustImport::Derive],
        "part 'user.g.dart';\n@Derive([CopyWith()])\nclass const User(final String _name, final String name) with _$User;\n",
    );
    for command in ["build", "check"] {
        let run = run_cli([command, "--root", workspace.path().to_str().unwrap()]);
        assert_eq!(run.exit_code, 1, "{}", run.stdout);
        assert!(
            run.stderr.contains("share public argument name `name`"),
            "{}",
            run.stderr
        );
        assert_eq!(std::fs::read_to_string(&output).unwrap(), previous);
    }
}

#[test]
fn primary_constructor_without_body_generates_exact_output() {
    let workspace = make_workspace();
    write_file(
        &workspace.path().join("pubspec.yaml"),
        "name: dust_test\nenvironment:\n  sdk: '>=3.13.0 <4.0.0'\n",
    );
    write_dust_file(
        &workspace.path().join("lib/user.dart"),
        &[DustImport::Derive],
        "part 'user.g.dart';\n@Derive([ToString()])\nclass const User(final String name) with _$User;\n",
    );
    let run = run_cli(["build", "--root", workspace.path().to_str().unwrap()]);
    assert_eq!(run.exit_code, 0, "{}", run.stderr);
    assert_eq!(
        std::fs::read_to_string(workspace.path().join("lib/user.g.dart")).unwrap(),
        r#"// GENERATED CODE - DO NOT MODIFY BY HAND
// coverage:ignore-file
// ignore_for_file: type=lint
// ignore_for_file: unused_element, unused_import, deprecated_member_use
// ignore_for_file: deprecated_member_use_from_same_package
// ignore_for_file: use_function_type_syntax_for_parameters
// ignore_for_file: unnecessary_const, avoid_init_to_null
// ignore_for_file: invalid_override_different_default_values_named
// ignore_for_file: prefer_expression_function_bodies
// ignore_for_file: annotate_overrides, invalid_annotation_target
// ignore_for_file: unnecessary_question_mark
// Generated by dust.

part of 'user.dart';

mixin _$User {
  @override
  String toString() {
    final self = this as User;
    return 'User('
        'name: ${self.name}'
        ')';
  }
}
"#,
    );
    let run = run_cli(["check", "--root", workspace.path().to_str().unwrap()]);
    assert_eq!(run.exit_code, 0, "{}", run.stderr);
    let output = workspace.path().join("lib/user.g.dart");
    let expected = std::fs::read(&output).unwrap();
    write_dust_file(
        &workspace.path().join("lib/user.dart"),
        &[DustImport::Derive],
        "part 'user.g.dart';\n@Derive([ToString()])\nclass const User.new(final String name) with _$User;\n",
    );
    for command in ["build", "check"] {
        let run = run_cli([command, "--root", workspace.path().to_str().unwrap()]);
        assert_eq!(run.exit_code, 0, "{}", run.stderr);
        assert_eq!(std::fs::read(&output).unwrap(), expected);
    }
}

#[test]
fn old_language_version_rejects_primary_without_creating_or_replacing_output() {
    for existing in [false, true] {
        let workspace = make_workspace();
        let input = workspace.path().join("lib/user.dart");
        let output = workspace.path().join("lib/user.g.dart");
        if existing {
            write_dust_file(
                &input,
                &[DustImport::Derive],
                "part 'user.g.dart';\n@Derive([ToString()])\nclass User with _$User { const User(this.name); final String name; }\n",
            );
            let run = run_cli(["build", "--root", workspace.path().to_str().unwrap()]);
            assert_eq!(run.exit_code, 0, "{}", run.stderr);
        }
        let previous = std::fs::read(&output).ok();
        assert_eq!(previous.is_some(), existing);
        write_file(
            &input,
            "// @dart=3.12\nimport 'package:dust_dart/derive.dart';\npart 'user.g.dart';\n@Derive([ToString()])\nclass const User(final String name) with _$User;\n",
        );
        for command in ["build", "check"] {
            let run = run_cli([command, "--root", workspace.path().to_str().unwrap()]);
            assert_eq!(run.exit_code, 1, "{command}: {}", run.stdout);
            assert!(run.stdout.is_empty());
            assert!(
                run.stderr.contains("primary constructors"),
                "{}",
                run.stderr
            );
            assert!(run.stderr.contains("3.13"), "{}", run.stderr);
            assert_eq!(std::fs::read(&output).ok(), previous);
        }
    }
}
