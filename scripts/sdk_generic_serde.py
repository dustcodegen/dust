"""Typed SerDe contracts in independently generated minimum/latest SDK consumers."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from sdk_codegen_fixtures import generated_hashes, generated_library_coverage
from sdk_generic_analysis import check_generic_analysis
from sdk_generic_names import require_only_name_infos
from sqlite_sdk_consumer import ROOT

STEMS = ("serde_basic", "serde_values", "serde_scope")


def require_serde_parity(rows: list[dict], primary: dict[str, dict]) -> None:
    """Neither SDK nor constructor spelling may silently erase or change helper scope."""
    for target in ("dart", "flutter"):
        outputs = [row["genericSerde"]["generated"] for row in rows if row["target"] == target]
        if (len(outputs) != 2 or not outputs[0] or outputs[0] != outputs[1]
                or outputs[0] != primary[target]["generated"]):
            raise ValueError(f"Missing or different traditional/primary {target} SerDe output")


def check_serde_types(run, dart: Path, app: Path, output: Path, env: dict[str, str]) -> list[str]:
    """Real kernel errors must reject erased returns, wrong receivers and bad bounds."""
    source = app / "lib/serde_basic.dart"
    original = source.read_bytes()
    cases = {
        "result": ("Phantom<int> value = _$PhantomDeserialize<num>({'label': 'x'});", ("can't be assigned", "Phantom<num>", "Phantom<int>")),
        "receiver": ("const $PhantomSerializer<int>().serialize(const Phantom<num>('x'));", ("can't be assigned", "Phantom<num>", "Phantom<int>")),
        "bound": ("_$PhantomFromJson<String>({'label': 'x'});", ("doesn't conform", "String", "num")),
        "codec": ("Phantom<int> value = const $PhantomDeserializer<num>().deserialize({'label': 'x'});", ("can't be assigned", "Phantom<num>", "Phantom<int>")),
    }
    try:
        for name, (body, markers) in cases.items():
            source.write_bytes(original + f"\nvoid main() {{ {body} }}\n".encode())
            result = run([str(dart), "compile", "kernel", str(source), "-o", str(output / f"{name}.dill")],
                         app, expected=254, env=env)
            message = result.stdout + result.stderr
            if result.returncode != 254 or "Error:" not in message or not all(marker in message for marker in markers):
                raise ValueError(f"Missing expected generic SerDe {name} type error")
    finally:
        source.write_bytes(original)
    return list(cases)


def check_generic_serde(run, dust: Path, dart: Path, app: Path, output: Path,
                        options: Path, package: str, env: dict[str, str], *,
                        primary: bool = False, flutter: list[str] | None = None) -> dict[str, object]:
    """Use only owned staging; restore every generated byte before comparing snapshots."""
    output.mkdir(parents=True, exist_ok=True)
    sources = [app / "lib" / f"{stem}.dart" for stem in STEMS]
    generated = [path.with_suffix(".g.dart") for path in sources]
    test = app / "test/serde_runtime_test.dart"
    owned = [*sources, *generated, test]
    if any(path.exists() for path in owned):
        raise ValueError("Generic SerDe requires fresh owned staging filenames")
    baseline = generated_hashes(app)
    fixtures = ROOT / "fixtures/generic_serde"
    style = "primary" if primary else "traditional"
    infos = []

    def analyze(command, cwd, env=None):
        result = run([str(dart), "analyze", "--format=machine", *command[3:], str(test)], cwd, env=env)
        infos.extend(require_only_name_infos(result.stdout + result.stderr))

    try:
        for path, name in zip(sources, (style, f"values_{style}", f"scope_{style}")):
            path.write_bytes((fixtures / f"{name}.dart.snapshot").read_bytes())
        content = (fixtures / "runtime_test.dart.snapshot").read_text().replace(
            "package:serde_probe/", f"package:{package}/")
        if flutter:
            content = content.replace("package:test/test.dart", "package:flutter_test/flutter_test.dart")
        test.write_text(content, encoding="utf-8")
        run([str(dust), "build", "--root", str(app)], app, env=env)
        run([str(dust), "check", "--root", str(app)], app, env=env)
        snapshots = {path: path.read_bytes() for path in generated}
        for path in owned:
            (output / path.name).write_bytes(path.read_bytes())
        check_generic_analysis(analyze, dart, app, options, "lib", env, stems=STEMS)
        report = output / "generated.lcov"
        try:
            if flutter:
                for path, source in snapshots.items():
                    path.write_bytes(source.replace(b"// coverage:ignore-file\n", b""))
                run([*flutter, "test", "--no-pub", "--coverage", f"--coverage-path={report}",
                     "--reporter=expanded", "test/serde_runtime_test.dart"], app, env=env)
            else:
                run([str(dart), "test", f"--coverage={output / 'coverage'}", "--reporter=expanded",
                     "test/serde_runtime_test.dart"], app, env=env)
                run([str(dart), "run", "coverage:format_coverage", "--package=.", "--lcov",
                     "-i", str(output / "coverage"), "-o", str(report), "--report-on=lib"], app, env=env)
        finally:
            for path, source in snapshots.items():
                path.write_bytes(source)
        coverage = generated_library_coverage(report, STEMS)
        negatives = check_serde_types(run, dart, app, output, env)
        for path, source in snapshots.items():
            expected = (fixtures / f"{path.stem.removesuffix('.g')}_generated.dart.snapshot").read_bytes()
            if source != expected:
                raise ValueError(f"Generic SerDe differs from the complete contract: {path.name}")
        current = generated_hashes(app)
        if any(current.get(name) != digest for name, digest in baseline.items()):
            raise ValueError("Generic SerDe changed baseline generated output")
        result = {"generated": {path.name: hashlib.sha256(source).hexdigest()
                                for path, source in snapshots.items()}, "nameStyleInfos": infos,
                  "generatedLineCoverage": coverage, "typeErrors": negatives}
        (output / "results.json").write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
        return result
    finally:
        for path in owned:
            path.unlink(missing_ok=True)
