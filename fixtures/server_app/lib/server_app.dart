/// A fixture for the server plugin, laid out in feature slices.
///
/// Each feature owns its DTO, model, repository, handlers, and router, so a
/// change to one stays in one directory. What is shared — the database, the
/// password and token primitives — sits under `shared/`.
///
/// ```text
/// bin/server.dart          the entry point
/// lib/src/
///   app.dart               mounts every feature's module
///   features/
///     accounts/            accounts_handler.dart -> accounts_handler.g.dart,
///                          credentials_dto, account_model, accounts_repo,
///                          require_scope
///     orders/              orders_handler.dart -> orders_handler.g.dart,
///                          new_order_dto, order_model, orders_repo
///     inventory/           inventory_handler.dart -> inventory_handler.g.dart,
///                          stock_model, inventory_repo
///     exports/             exports_handler.dart -> exports_handler.g.dart
///   shared/
///     auth/                passwords, tokens
///     db/                  database.dart -> database.g.dart
/// ```
///
/// The models, repositories, and database `.g.dart` files are generated by
/// `dust build`. The `*_handler.g.dart` files remain hand-written contracts for
/// later server phases such as custom extractors, state, raw bodies, and
/// streams. The smaller `fixtures/server_codegen_app` package is generated by
/// the integrated Phase 1 plugin.
///
